import tkinter as tk

#Q1
root = tk.Tk()
root.title("My First GUI")
root.geometry("300x200")
label = tk.Label(root, text="Enter your name:")
label.pack()
entry = tk.Entry(root)
entry.pack()
button = tk.Button(root, text="Submit")
button.pack()
root.mainloop()

